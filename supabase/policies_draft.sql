٣) الطلبات
• يلتزم العميل بتقديم بيانات صحيحة (الاسم، الهاتف، العنوان).
• قد نتواصل معك هاتفياً لتأكيد الطلب قبل الشحن.
• يحق للمتجر إلغاء الطلب في حالة عدم توفر المنتج أو وجود خطأ واضح في السعر، مع رد أي مبلغ مدفوع بالكامل.

٤) الدفع
• طرق الدفع المتاحة تظهر في صفحة إتمام الطلب (الدفع عند الاستلام، والبطاقات البنكية، والمحافظ والتحويلات عند تفعيلها).
