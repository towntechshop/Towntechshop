• توفّر المنتجات يتغير باستمرار، والكمية المعروضة هي المتاحة وقت التصفح.

٢) الأسعار
• جميع الأسعار بالجنيه المصري.
• الأسعار قابلة للتغيير دون إشعار مسبق، ويُعتمد السعر الظاهر وقت تأكيد الطلب.
